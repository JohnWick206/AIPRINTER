# Render the Chinese glyphs used by the status screen into a 32x32 1bpp C table.
# ASCII only on purpose: Windows PowerShell 5.1 parses .ps1 as GBK, so any
# multi-byte literal here would corrupt the quotes.

Add-Type -AssemblyName System.Drawing

# U+8FDE Lian, U+63A5 Jie, U+4E2D Zhong, U+5C31 Jiu, U+7EEA Xu,
# U+751F Sheng, U+6210 Cheng, U+4E0B Xia, U+8F7D Zai, U+89E3 Jie,
# U+7801 Ma, U+51FA Chu, U+9519 Cuo, U+9650 Xian, U+6D41 Liu,
# U+542F Qi, U+52A8 Dong, U+5B8C Wan, U+7B49 Deng, U+5F85 Dai
$codes = @(
  0x8FDE, 0x63A5, 0x4E2D, 0x5C31, 0x7EEA,
  0x751F, 0x6210, 0x4E0B, 0x8F7D, 0x89E3,
  0x7801, 0x51FA, 0x9519, 0x9650, 0x6D41,
  0x542F, 0x52A8, 0x5B8C, 0x7B49, 0x5F85
)

$SS = 128          # supersample box
$OUT = 32          # final glyph box
$FONT_PX = 104     # em size inside the supersample box
$THRESH = 110      # ink threshold after downsampling

$font = New-Object System.Drawing.Font("SimHei", $FONT_PX, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$fmt = New-Object System.Drawing.StringFormat
$fmt.Alignment = [System.Drawing.StringAlignment]::Center
$fmt.LineAlignment = [System.Drawing.StringAlignment]::Center
$rect = New-Object System.Drawing.RectangleF(0, 0, $SS, $SS)

$allBits = New-Object System.Collections.ArrayList

foreach ($cp in $codes) {
  $ch = [string][char]$cp

  $big = New-Object System.Drawing.Bitmap($SS, $SS)
  $g = [System.Drawing.Graphics]::FromImage($big)
  $g.Clear([System.Drawing.Color]::Black)
  $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAlias
  $g.DrawString($ch, $font, [System.Drawing.Brushes]::White, $rect, $fmt)
  $g.Dispose()

  $small = New-Object System.Drawing.Bitmap($OUT, $OUT)
  $g2 = [System.Drawing.Graphics]::FromImage($small)
  $g2.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  $g2.DrawImage($big, 0, 0, $OUT, $OUT)
  $g2.Dispose()
  $big.Dispose()

  $bits = New-Object 'byte[]' 128
  $inkCount = 0
  for ($y = 0; $y -lt $OUT; $y++) {
    for ($x = 0; $x -lt $OUT; $x++) {
      $c = $small.GetPixel($x, $y)
      if ($c.R -gt $THRESH) {
        $byteIdx = $y * 4 + [int]($x / 8)
        $bits[$byteIdx] = $bits[$byteIdx] -bor (0x80 -shr ($x % 8))
        $inkCount++
      }
    }
  }
  $small.Dispose()
  [void]$allBits.Add(@{ cp = $cp; bits = $bits; ink = $inkCount })
  Write-Output ("U+{0:X4}  ink={1}" -f $cp, $inkCount)
}

# ---- preview: 4x nearest neighbour, all glyphs in one strip ----
$scale = 4
$gap = 6
$w = $codes.Count * ($OUT * $scale + $gap) + $gap
$h = $OUT * $scale + 2 * $gap + 24
$preview = New-Object System.Drawing.Bitmap($w, $h)
$pg = [System.Drawing.Graphics]::FromImage($preview)
$pg.Clear([System.Drawing.Color]::FromArgb(24, 24, 28))
$labelFont = New-Object System.Drawing.Font("Consolas", 12, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$labelBrush = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(140, 200, 240))
$white = [System.Drawing.Brushes]::White

for ($i = 0; $i -lt $allBits.Count; $i++) {
  $item = $allBits[$i]
  $ox = $gap + $i * ($OUT * $scale + $gap)
  $oy = $gap
  for ($y = 0; $y -lt $OUT; $y++) {
    for ($x = 0; $x -lt $OUT; $x++) {
      $byteIdx = $y * 4 + [int]($x / 8)
      $on = ($item.bits[$byteIdx] -band (0x80 -shr ($x % 8))) -ne 0
      if ($on) {
        $pg.FillRectangle($white, $ox + $x * $scale, $oy + $y * $scale, $scale, $scale)
      }
    }
  }
  $pg.DrawString(("U+{0:X4}" -f $item.cp), $labelFont, $labelBrush, $ox, $oy + $OUT * $scale + 4)
}
$pg.Dispose()
$preview.Save("D:\sticker\idf\net_speed\font_preview.png", [System.Drawing.Imaging.ImageFormat]::Png)
$preview.Dispose()

# ---- emit C header ----
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// 32x32 1bpp Chinese glyphs for the status screen.")
[void]$sb.AppendLine("// Generated by gen_font.ps1 from SimHei, downsampled and thresholded.")
[void]$sb.AppendLine("// Do not edit by hand.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#include <stdint.h>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("typedef struct {")
[void]$sb.AppendLine("    uint32_t cp;        // Unicode code point")
[void]$sb.AppendLine("    uint8_t  bits[128]; // 32x32, 4 bytes per row, MSB on the left")
[void]$sb.AppendLine("} cn_glyph_t;")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("static const cn_glyph_t s_cn_glyphs[] = {")

foreach ($item in $allBits) {
  [void]$sb.AppendLine(("    {{ 0x{0:X4}, {{" -f $item.cp))
  for ($r = 0; $r -lt 32; $r++) {
    $line = "        "
    for ($b = 0; $b -lt 4; $b++) {
      $line += ("0x{0:X2}, " -f $item.bits[$r * 4 + $b])
    }
    [void]$sb.AppendLine($line.TrimEnd())
  }
  [void]$sb.AppendLine("    } },")
}

[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#define CN_GLYPH_COUNT ((int)(sizeof(s_cn_glyphs)/sizeof(s_cn_glyphs[0])))")

[System.IO.File]::WriteAllText("D:\sticker\idf\net_speed\main\font_cn.h", $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote font_cn.h"
